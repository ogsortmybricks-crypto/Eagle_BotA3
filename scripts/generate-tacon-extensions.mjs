/**
 * Discover trusted, checked-in Tac-On implementations at build time.
 * Never scans uploads, databases or user-controlled source paths.
 */
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../built-tacons/", import.meta.url));
const entries = [];
for (const folder of (await readdir(root, { withFileTypes: true })).filter(entry => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const descriptor = path.join(root, folder.name, "extension.json");
  let metadata;
  try { metadata = JSON.parse(await readFile(descriptor, "utf8")); }
  catch (error) { if (error.code === "ENOENT") continue; throw error; }
  if (metadata.id !== folder.name || !/^[a-z][a-z0-9-]{1,48}$/.test(metadata.id)) {
    throw new Error(`Invalid extension id in ${folder.name}.`);
  }
  for (const kind of ["compiler", "server", "client"]) {
    const file = metadata[kind];
    if (typeof file !== "string" || !/^extension\.[a-z]+\.(ts|tsx)$/.test(file)) throw new Error(`Invalid ${kind} entry in ${folder.name}.`);
    const entry = await stat(path.join(root, folder.name, file));
    if (!entry.isFile()) throw new Error(`Missing ${kind} entry in ${folder.name}.`);
  }
  entries.push(metadata);
}
for (const kind of ["compiler", "server", "client"]) {
  const output = [
    "// Generated by scripts/generate-tacon-extensions.mjs. Do not edit.",
    "// All executable implementations live in their checked-in Tac-On folders.",
    ...entries.map((entry, index) => `import extension${index} from "./${entry.id}/${entry[kind].replace(/\.tsx?$/, "")}";`),
    `export const extensions = [${entries.map((_, index) => `extension${index}`).join(", ")}];`,
    "",
  ].join("\n");
  const destination = path.join(root, `extensions.${kind}.generated.ts`);
  let previous = "";
  try { previous = await readFile(destination, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (previous !== output) await writeFile(destination, output);
}
console.log(`Registered ${entries.length} trusted Tac-On extension${entries.length === 1 ? "" : "s"}.`);
